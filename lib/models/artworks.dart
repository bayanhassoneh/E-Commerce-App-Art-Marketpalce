class Artwork {
  final String id;
  final String artistId;
  final String title;
  final double price;
  final String description;
  final String imageUrl;
  final String createdAt;

  Artwork({
    required this.id,
    required this.artistId,
    required this.title,
    required this.price,
    required this.description,
    required this.imageUrl,
    required this.createdAt,
  });
}
